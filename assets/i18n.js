/* Lingua salvata a mano dal selettore, se presente, altrimenti la prima fra
   le lingue del browser che il sito supporta, altrimenti l'inglese. */
function detectLocale() {
  try {
    const saved = localStorage.getItem(LANG_STORE);
    if (saved && DICT[saved]) return saved;
  } catch { /* localStorage non disponibile */ }

  for (const lang of navigator.languages || [navigator.language || 'en']) {
    const base = lang.slice(0, 2).toLowerCase();
    if (DICT[base]) return base;
  }
  return 'en';
}

let currentLocale = detectLocale();

function setLocale(code) {
  if (!DICT[code]) return;
  currentLocale = code;
  try { localStorage.setItem(LANG_STORE, code); } catch { /* spazio esaurito */ }
}

function localeTag() {
  return LOCALE_TAG[currentLocale] || 'en-US';
}

function fillParams(str, params) {
  if (!params) return str;
  return str.replace(/\{(\w+)\}/g, (m, key) => (key in params ? params[key] : m));
}

/* Stringa semplice, con eventuali {segnaposto}. Ricade sull'inglese e poi
   sulla chiave stessa se la traduzione manca. */
function t(key, params) {
  const str = DICT[currentLocale]?.[key] ?? DICT.en[key] ?? key;
  return fillParams(str, params);
}

/* Come t(), ma la voce del dizionario è { one, other } scelta in base a n.
   Cinese e giapponese non distinguono singolare e plurale: le loro voci
   hanno one === other, quindi la stessa logica va bene per tutte le lingue. */
function tn(key, n, params) {
  const entry = DICT[currentLocale]?.[key] ?? DICT.en[key];
  const form = n === 1 ? entry.one : entry.other;
  return fillParams(form, { n, ...params });
}

/* Applica tutti i testi statici marcati nel markup. Va richiamata anche dopo
   un cambio di lingua dal selettore. */
function applyStaticTranslations() {
  document.documentElement.lang = currentLocale;

  for (const node of document.querySelectorAll('[data-i18n]')) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of document.querySelectorAll('[data-i18n-html]')) {
    node.innerHTML = t(node.dataset.i18nHtml);
  }
  for (const node of document.querySelectorAll('[data-i18n-placeholder]')) {
    node.placeholder = t(node.dataset.i18nPlaceholder);
  }
  for (const node of document.querySelectorAll('[data-i18n-title]')) {
    node.title = t(node.dataset.i18nTitle);
  }
  for (const node of document.querySelectorAll('[data-i18n-aria-label]')) {
    node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  }

  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.content = t('meta_description');
}
